// HORNER: 3 groups of 5 digits per lane -> limbs in dwords 0..2 of each lane.
// Y8/Y9 = gathers, Y10/Y11/Y12 = (58,1), (3364,1), 58.
#define HORNER(v, p, q) \
	VPSHUFB Y8, v, p; VPSHUFB Y9, v, q; \
	VPMADDUBSW Y10, p, p; VPMADDWD Y11, p, p; VPMULLD Y12, p, p; VPADDD q, p, p

